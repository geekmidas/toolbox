import { mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import type {
	WebSocketApiDeclaration,
	WebSocketRouteInfo,
} from '@geekmidas/manifest';
import type { ConstructSource } from '../reconcile/discover.js';

/**
 * The route keys a surface on API Gateway always has, declared or not: the
 * adaptor's `$connect` checks the Origin and writes the connection table, and
 * its `$disconnect` deletes the row — so a surface with no connect handler
 * still has a table a broadcast can read.
 */
const LIFECYCLE = ['$connect', '$disconnect'] as const;

/**
 * One Lambda per route of a WebSocket surface, for API Gateway.
 *
 * Each imports the surface and its own route — nothing else — and serves it
 * through `AmazonApiGatewayWebSocket`, so a route's Lambda reaches what that
 * route depends on, as an endpoint's does. `$connect` and `$disconnect` are
 * written whether the surface declares them or not.
 *
 * `outputDir` is the app's `.gkm/aws`; the handlers go under `websocket/`,
 * which is emptied first so a deleted route's handler goes with it. The
 * handler paths returned are measured from `workspaceRoot`, as an endpoint's.
 */
export async function writeWebSocketLambdas(input: {
	outputDir: string;
	appRoot: string;
	workspaceRoot: string;
	surface: ConstructSource;
	declaration: WebSocketApiDeclaration;
}): Promise<WebSocketRouteInfo[]> {
	const { outputDir, appRoot, workspaceRoot, surface, declaration } = input;
	const dir = join(outputDir, 'websocket');
	await rm(dir, { recursive: true, force: true });
	await mkdir(dir, { recursive: true });

	const declared = new Map(
		(declaration.routes ?? []).map((route) => [route.action, route]),
	);
	const actions = [
		...LIFECYCLE,
		...[...declared.keys()].filter(
			(action) => !(LIFECYCLE as readonly string[]).includes(action),
		),
	];

	const infos: WebSocketRouteInfo[] = [];
	const taken = new Set<string>();
	for (const action of actions) {
		const route = declared.get(action);
		let name = fileNameOf(action);
		// `chat.send` and `chat_send` are two actions and one file name.
		for (let n = 2; taken.has(name); n++) name = `${fileNameOf(action)}-${n}`;
		taken.add(name);
		const file = join(dir, `${name}.ts`);
		// Discovery wrote `<file>#<export>`, relative to the app.
		const [source, exportName] = route?.handler.split('#') ?? [];
		await writeFile(
			file,
			lambdaSource({
				from: dirname(file),
				surface,
				route:
					source && exportName
						? { file: resolve(appRoot, source), exportName }
						: undefined,
			}),
		);
		infos.push({
			surface: declaration.id,
			action,
			handler: relative(workspaceRoot, file).replace(/\.ts$/, '.handler'),
		});
	}
	return infos;
}

/**
 * A file name for a route key: `$connect` → `connect`, `chat.send` →
 * `route-chat_send`, so no action can take a lifecycle route's file, and a
 * handler path has one dot — the one before its export.
 */
export function fileNameOf(action: string): string {
	if (action.startsWith('$')) return action.slice(1);
	return `route-${action.replace(/[^A-Za-z0-9-]/g, '_')}`;
}

function specifierOf(from: string, file: string): string {
	const rel = relative(from, file).replace(/\.ts$/, '.js');
	return rel.startsWith('.') ? rel : `./${rel}`;
}

function lambdaSource(input: {
	from: string;
	surface: ConstructSource;
	route?: { file: string; exportName: string };
}): string {
	const { from, surface, route } = input;
	const routeImport = route
		? `import { ${route.exportName} as route } from '${specifierOf(from, route.file)}';\n`
		: '';
	const modules = route ? '[{ route }]' : '[]';
	return `/**
 * Generated by 'gkm build --provider aws': one route of a WebSocket surface,
 * as API Gateway invokes it.
 */
import { AmazonApiGatewayWebSocket } from '@geekmidas/constructs/aws';
import { ${surface.exportName} as surface } from '${specifierOf(from, surface.file)}';
${routeImport}
const adaptor = new AmazonApiGatewayWebSocket(surface, { modules: ${modules} });

export const handler = adaptor.handler;
`;
}
