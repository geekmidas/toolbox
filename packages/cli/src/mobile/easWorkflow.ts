/**
 * A stage's EAS workflow (`.eas/workflows/publish-<stage>.yml`): what
 * `gkm publish` does, run by EAS itself — so shipping the app needs no CI
 * of the project's own, no runner and no token in GitHub.
 *
 * Per platform: the native code's fingerprint, read with the stage's EAS
 * environment; a finished store build of the stage's profile with that
 * fingerprint; then an update on the stage's channel when there is one, or
 * a store build, submitted with the stage's submit profile, when there is
 * not. iOS is submitted once `submit.<stage>.ios.ascAppId` is set — until
 * then it is built and not submitted.
 *
 * It runs when the stage is deployed: the protected stage on a release tag
 * (`v*`), every other deployed stage on a push to `main` — and on demand,
 * `eas workflow:run .eas/workflows/publish-<stage>.yml`. The values a build
 * reads are the stage's EAS environment, which `gkm eas:sync` keeps.
 *
 * Generated: written by `gkm eas:sync`, and overwritten by the next one.
 */

import { stringify } from 'yaml';
import type { EasPlatform } from './eas.js';
import type { MobileStage } from './stage.js';

/** Where a stage's workflow is written, relative to the app. */
export function easWorkflowPath(stage: string): string {
	return `.eas/workflows/publish-${stage}.yml`;
}

/** The stage's EAS workflow, as YAML. */
export function easWorkflow(
	stage: MobileStage,
	options: {
		/** Whether this is the stage a release deploys — the protected one. */
		release: boolean;
		/** Whether iOS builds are submitted: the stage's ascAppId is set. */
		iosSubmits: boolean;
		/**
		 * Whether the workspace pins its package manager (package.json's
		 * `packageManager`): EAS's machines then install with that version,
		 * through corepack, as a build profile's `corepack: true` does.
		 */
		corepack?: boolean;
	},
): string {
	const profile = stage.stage;
	const jobs: Record<string, unknown> = {
		fingerprint: {
			name: 'Fingerprint',
			type: 'fingerprint',
			environment: stage.environment,
		},
	};
	for (const platform of ['android', 'ios'] as EasPlatform[]) {
		const existing = `get_${platform}_build`;
		const build = `build_${platform}`;
		const name = platform === 'ios' ? 'iOS' : 'Android';
		jobs[existing] = {
			name: `Find an ${name} store build with this native code`,
			needs: ['fingerprint'],
			type: 'get-build',
			params: {
				fingerprint_hash: `\${{ needs.fingerprint.outputs.${platform}_fingerprint_hash }}`,
				profile,
				platform,
				distribution: 'store',
			},
		};
		jobs[build] = {
			name: `Build ${name}`,
			needs: [existing],
			if: `\${{ !needs.${existing}.outputs.build_id }}`,
			type: 'build',
			params: { platform, profile },
		};
		if (platform === 'android' || options.iosSubmits) {
			jobs[`submit_${platform}`] = {
				name: `Submit ${name}`,
				needs: [build],
				type: 'submit',
				params: {
					build_id: `\${{ needs.${build}.outputs.build_id }}`,
					profile,
				},
			};
		}
		jobs[`update_${platform}`] = {
			name: `Update ${name} on '${stage.channel}'`,
			needs: [existing],
			if: `\${{ needs.${existing}.outputs.build_id }}`,
			type: 'update',
			environment: stage.environment,
			params: { platform, channel: stage.channel },
		};
	}

	const header = [
		`# Generated by \`gkm eas:sync --stage ${stage.stage}\`: run it again rather than`,
		'# editing this file. An update when a store build has this native code,',
		`# a store build submitted to the stores when none does. Run by hand:`,
		`#   eas workflow:run ${easWorkflowPath(stage.stage)}`,
		'',
	].join('\n');
	return `${header}${stringify(
		{
			name: `Publish to ${stage.stage}`,
			on: options.release
				? { push: { tags: ['v*'] } }
				: { push: { branches: ['main'] } },
			...(options.corepack ? { defaults: { tools: { corepack: true } } } : {}),
			jobs,
		},
		{ lineWidth: 0 },
	)}`;
}
